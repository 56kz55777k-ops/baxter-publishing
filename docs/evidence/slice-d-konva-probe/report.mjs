// Slice D stage 1 probe — renders results/summary.md from results.json. NOT production code. Deterministic: no
// timings or timestamps, so a rerun on the same environment reproduces the file byte for byte.
import { TOL } from './analyse.mjs';

const fmtN = (x) => (x === null || x === undefined || x === Infinity ? '—' : x === 0 ? '0' : Math.abs(x) < 1e-3 ? x.toExponential(2) : String(+x.toFixed(6)));
const fmtB = (B) => (B ? `${B.x / 100}, ${B.y / 100}, ${B.w / 100} × ${B.h / 100}` : '—');

export function renderSummary(results, cases) {
  const names = Object.keys(results.browsers);
  const L = [];
  const p = (s = '') => L.push(s);
  p('# Slice D stage 1 — isolated Konva probe: results');
  p();
  p('Generated by `node docs/evidence/slice-d-konva-probe/run-probe.mjs`. Real Playwright pointer and keyboard input unless a case is marked *programmatic* (supplementary) or *mixed* (its notes say which steps). Every delivered move is replayed through the reviewed model (`docs/evidence/slice-d-math-check.js`, shared section, unmodified) and compared with what Konva did.');
  p();
  if (results.env.negativeControl) { p(`**NEGATIVE CONTROL RUN: the Node-side model was deliberately mutated (${results.env.negativeControl}); failures are the expected outcome. Not the recorded probe result.**`); p(); }
  p('## Environment');
  p();
  const e = results.env;
  p(`- OS: ${e.os}`);
  p(`- Node: ${e.node}`);
  p(`- Playwright: ${e.playwright}`);
  for (const n of names) {
    const B = results.browsers[n];
    p(B.launchError ? `- ${n}: **could not launch** — ${B.launchError}` : `- ${n}: ${B.version} — \`${B.userAgent}\` (page reports Konva ${B.pageKonvaVersion})`);
  }
  p(`- Konva: ${e.konva.version}, ${e.konva.served}; lockfile integrity \`${e.konva.lockIntegrity}\` = installed \`${e.konva.installedIntegrity}\``);
  for (const [f, h] of Object.entries(e.konva.files)) p(`  - \`${f}\` sha256 \`${h}\``);
  p(`- Model: \`${e.model.file}\` sha256 \`${e.model.sha256}\`; shared section (${e.model.sharedSectionLines} lines, served to the page and loaded in Node) sha256 \`${e.model.sharedSectionSha256}\``);
  p(`- Probe files: ${Object.entries(e.probeFiles).map(([f, h]) => `\`${f}\` ${h.slice(0, 12)}`).join(', ')}`);
  p();
  p('## Totals');
  p();
  p('| Browser | PASS | FAIL | NOT EXECUTED | page errors |');
  p('|---|---|---|---|---|');
  for (const n of names) {
    const B = results.browsers[n];
    if (B.launchError) { p(`| ${n} | — | — | all (did not launch) | — |`); continue; }
    const c = (s) => B.cases.filter((x) => x.status === s).length;
    p(`| ${n} | ${c('PASS')} | ${c('FAIL')} | ${c('NOT EXECUTED')} | ${B.pageErrors.length} |`);
  }
  p();
  p('## Matrix');
  p();
  p(`| Case | Kind | What | ${names.join(' | ')} |`);
  p(`|---|---|---|${names.map(() => '---').join('|')}|`);
  for (const c of cases) {
    const cells = names.map((n) => { const B = results.browsers[n]; if (B.launchError) return 'NOT EXECUTED'; const s = B.cases.find((x) => x.id === c.id); return s ? s.status : '—'; });
    p(`| ${c.id} | ${c.kind} | ${c.title.replace(/\|/g, '/')} | ${cells.join(' | ')} |`);
  }
  p();
  p('## Measured agreement (all cases, per browser)');
  p();
  p(`Tolerances: returned anchor target ≤ ${TOL.target} px; Konva anchor / oldBox vs model box ≤ ${TOL.anchor} px; Konva proposed box vs port ≤ ${TOL.raw} px; Konva comparePoint vs our fixed corner ≤ ${TOL.compare} px; Konva centre vs our carried centre ≤ 0.005 mm; client rect after onTransform ≤ ${TOL.rect} px. Bounded boxes, anchor names, skip/proceed, freeze, segment keys and references: exact.`);
  p();
  p('| Measure | ' + names.join(' | ') + ' |');
  p('|---|' + names.map(() => '---').join('|') + '|');
  const agg = {};
  for (const n of names) {
    const B = results.browsers[n];
    const a = { moves: 0, pending: 0, unchanged: 0, skip: 0, proceed: 0, frozen: 0, renamed: 0, clamped: 0, maxTarget: 0, maxRaw: 0, maxAnchor: 0, maxRect: 0, maxCompare: 0, compareN: 0, maxCentre: 0, centreN: 0, agree: 0, disagree: 0, twin: 0, diffs: 0, minClampExtent: Infinity, maxMirror: 0, mirrorN: 0 };
    for (const s of B.cases || []) {
      const m = s.metrics;
      for (const k of ['moves', 'pending', 'unchanged', 'skip', 'proceed', 'frozen', 'renamed', 'clamped', 'compareN', 'centreN', 'diffs', 'mirrorN']) a[k] += m[k];
      a.minClampExtent = Math.min(a.minClampExtent, m.minClampExtent ?? Infinity); a.maxMirror = Math.max(a.maxMirror, m.maxMirror ?? 0);
      a.twin += m.twinChecked; a.agree += m.unchangedPredictedAgree; a.disagree += m.unchangedPredictedDisagree;
      for (const k of ['maxTarget', 'maxRaw', 'maxAnchor', 'maxRect']) a[k] = Math.max(a[k], m[k]);
      a.maxCompare = Math.max(a.maxCompare, m.maxCompare ?? 0); a.maxCentre = Math.max(a.maxCentre, m.maxCentre ?? 0);
    }
    agg[n] = a;
  }
  const row = (label, f) => p(`| ${label} | ${names.map((n) => (results.browsers[n].launchError ? '—' : f(agg[n]))).join(' | ')} |`);
  row('moves through anchorDragBoundFunc', (a) => a.moves);
  row('— threshold pending (returned oldAbs; Konva did nothing)', (a) => a.pending);
  row('— Konva returned early, anchor unchanged', (a) => `${a.unchanged} (model predicted ${a.agree}, not predicted ${a.disagree})`);
  row('— Konva [-1, 1) px skip', (a) => a.skip);
  row('— boundBoxFunc ran', (a) => a.proceed);
  row('— of which frozen (drag-through) / renamed', (a) => `${a.frozen} / ${a.renamed}`);
  row('— ratio anchor clamp engaged', (a) => a.clamped);
  row('moves replayed through the evidence gestureMove twin', (a) => a.twin);
  row('max |returned target − model| px', (a) => fmtN(a.maxTarget));
  row('max |Konva proposed box − port| px', (a) => fmtN(a.maxRaw));
  row('max |Konva anchor / oldBox − model box| px', (a) => fmtN(a.maxAnchor));
  row('max |Konva comparePoint − fixed corner| px (one-edge ratio moves)', (a) => `${fmtN(a.maxCompare)} (${a.compareN} moves)`);
  row('smallest clamp extent (minimum box side) px, for comparison', (a) => fmtN(a.minClampExtent));
  row('max |Konva centre − carried centre| px (Alt moves; ≤ 0.005 mm expected)', (a) => `${fmtN(a.maxCentre)} (${a.centreN} moves)`);
  row('max |Konva centred-box centre − current box centre| px (Alt mirroring)', (a) => `${fmtN(a.maxMirror)} (${a.mirrorN} moves)`);
  row('max |client rect − bounded box| px', (a) => fmtN(a.maxRect));
  row('per-move differences from the model', (a) => a.diffs);
  p();
  p('## Konva early-return boundary (real pointer events)');
  p();
  p('Pointer coordinates are integers; the exact sub-pixel extent comes from the node geometry (32 mm on the tested axis at zoom (v + 40)/32 px/mm, a 40 px move). "Tested" is the exact value Konva passed to `Util._inRange(v, -1, 1)`.');
  p();
  p(`| Case | ${names.map((n) => `${n}: pointer → tested → outcome`).join(' | ')} |`);
  p(`|---|${names.map(() => '---').join('|')}|`);
  for (const c of cases.filter((x) => x.group === 'H')) {
    const cells = names.map((n) => {
      const B = results.browsers[n]; if (B.launchError) return 'NOT EXECUTED';
      const s = B.cases.find((x) => x.id === c.id); if (!s) return '—';
      const b = s.extra && s.extra.boundary; if (!b) return s.status;
      const outc = b.cls === 'skip' ? 'skip (box held)' : `${b.frozen ? 'freeze + rename → ' + b.anchorAfter : 'bounded ' + (b.box ? fmtB({ x: b.box[0], y: b.box[1], w: b.box[2], h: b.box[3] }) : '')}`;
      return `(${b.delivered.join(', ')}) → ${b.konvaTested} → ${outc} — **${s.status}**`;
    });
    p(`| ${c.id} | ${cells.join(' | ')} |`);
  }
  p();
  p('## Crossing-and-return paths (real pointer events, measured part after the lead-in)');
  p();
  p('| Path | Browser | moves | freezes | renames | clamped | skips | out/back mismatches | max edge jump (mm) | start → back at start | smallest box | status |');
  p('|---|---|---|---|---|---|---|---|---|---|---|---|');
  for (const c of cases.filter((x) => x.group === 'E')) {
    for (const n of names) {
      const B = results.browsers[n]; if (B.launchError) continue;
      const s = B.cases.find((x) => x.id === c.id); if (!s) continue;
      const R = s.extra && s.extra.path;
      if (!R) { p(`| ${c.id} | ${n} | ${s.info.join('; ')} | | | | | | | | | ${s.status} |`); continue; }
      const small = c.id === 'E11' ? R.minByH : R.minByW;
      p(`| ${c.id} | ${n} | ${R.measuredMoves} | ${R.freezes} | ${R.renames} | ${R.clamps} | ${R.skips} | ${R.returnMismatch} | ${R.maxJump.toFixed(2)} | ${fmtB(R.start)} → ${fmtB(R.final)} | ${fmtB(small)} | ${s.status} |`);
    }
  }
  p();
  p('## Per-case notes');
  p();
  for (const c of cases) {
    p(`### ${c.id} — ${c.title}`);
    p();
    p(`Kind: ${c.kind}.${c.notes ? ' ' + c.notes + '.' : ''}`);
    p();
    for (const n of names) {
      const B = results.browsers[n];
      if (B.launchError) { p(`- **${n}: NOT EXECUTED** (browser did not launch)`); continue; }
      const s = B.cases.find((x) => x.id === c.id);
      if (!s) continue;
      p(`- **${n}: ${s.status}**${s.notExecuted ? ' — ' + s.notExecuted : ''}`);
      for (const i of s.info) p(`  - ${i}`);
      for (const f of s.failures) p(`  - FAIL: ${f}`);
    }
    p();
  }
  p('## Page errors');
  p();
  for (const n of names) {
    const B = results.browsers[n];
    if (B.launchError) continue;
    p(`- ${n}: ${B.pageErrors.length ? B.pageErrors.join(' | ') : 'none'}`);
  }
  p();
  return L.join('\n');
}
